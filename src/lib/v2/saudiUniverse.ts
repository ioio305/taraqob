export const SAUDI_NOMU: SaudiStockMeta[] = NOMU_RAW.map(([code, name, sector]) => ({
  symbol: `${code}.SR`, name, sector: SAUDI_SECTORS[sector],
}))

export const SAUDI_FUNDS: SaudiStockMeta[] = FUNDS_RAW.map(([code, name, category]) => ({
  symbol: `${code}.SR`, name, sector: SAUDI_FUND_CATEGORIES[category],
}))

export const SEGMENT_LIST: Record<SaudiSegment, SaudiStockMeta[]> = {
  main: SAUDI_STOCKS,
  nomu: SAUDI_NOMU,
  funds: SAUDI_FUNDS,
}

// بحث بالرمز المجرّد في كل الإدراجات (الرئيسية + نمو + الصناديق) — للمحفظة والتنبيهات وصفحة السهم.
export const SAUDI_ANY: Record<string, { name: string; sector: string; segment: SaudiSegment }> = Object.fromEntries(
  (Object.keys(SEGMENT_LIST) as SaudiSegment[]).flatMap(segment =>
    SEGMENT_LIST[segment].map(s => [s.symbol.replace('.SR', ''), { name: s.name, sector: s.sector, segment }])),
)

export const SAUDI_ALL_LISTINGS: Array<SaudiStockMeta & { segment: SaudiSegment }> =
  (Object.keys(SEGMENT_LIST) as SaudiSegment[]).flatMap(segment => SEGMENT_LIST[segment].map(s => ({ ...s, segment })))

export function segmentOf(code: string): SaudiSegment | null {
  return SAUDI_ANY[code.replace('.SR', '')]?.segment ?? null
}

export function parseSegment(v: unknown): SaudiSegment | null {
  return v === 'main' || v === 'nomu' || v === 'funds' ? v : null
}

// منصة المسار الحالي داخل /saudi (الافتراضي السوق الرئيسية).
export function segmentOfPath(path: string): SaudiSegment {
  if (path === '/saudi/nomu' || path.startsWith('/saudi/nomu/')) return 'nomu'
  if (path === '/saudi/funds' || path.startsWith('/saudi/funds/')) return 'funds'
  return 'main'
}
