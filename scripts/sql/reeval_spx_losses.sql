-- بلغ الهدف الأول ثم انعكس حُسب خاسراً. الآن القاعدة صحيحة (بلوغ الهدف = نجاح).
-- هذا الملف يعيد العقود المسجّلة «خسارة» إلى active كي يعيد كرون التقييم
-- (/api/v2/signals/evaluate — يعمل تلقائياً أيام العمل 21:30 UTC) تصنيفها بالقاعدة الصحيحة.
