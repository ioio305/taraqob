-- شغّله في: Supabase Dashboard → SQL Editor (مشروع ترقب). آمن، لا يحذف بيانات.
-- لا نلمس closed_win (نجاحات مؤكدة تبقى نجاحات) ولا expired (لم تلمس شيئاً).
-- ══════════════════════════════════════════════════════════════════════════

-- 1) كم عقداً مسجّلاً «خسارة» سيُعاد تقييمه؟ (للاطّلاع قبل التحديث)
select count(*) as losses_to_reeval
from public.v2_signals
where status = 'closed_loss';

-- 2) أعِدها إلى active — سيعيد الكرون تقييمها بالقاعدة المصحّحة
update public.v2_signals
set status = 'active'
where status = 'closed_loss';

